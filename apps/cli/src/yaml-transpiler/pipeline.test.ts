/**
 * Regression tests for issue #2209 — a suite file's `base_url` never reached the
 * generated spec, so every relative `URL:` failed at runtime.
 *
 * `base_url` is documented in the YAML spec §3 as a TOP-LEVEL key that maps to
 * `test.use({ baseURL })`, with no suite exception. The suite parser only ever
 * read the undocumented nested `suite.base_url` (written by `suiteToYaml` on the
 * debugger round-trip), so the documented form was silently discarded.
 */
describe('suite base_url → test.use({ baseURL })', () => {
  const suiteTmpDir = join(tmpdir(), 'suite-baseurl-test-' + Date.now());
  mkdirSync(suiteTmpDir, { recursive: true });

  after(() => {
    rmSync(suiteTmpDir, { recursive: true, force: true });
  });

  const suiteBody = `
suite:
  beforeEach:
    - URL: /
  tests:
    - name: anything
      statements:
        - VERIFY: The page loaded
          js: "await expect(page).toHaveURL(/example/)"
`;

  function transpileSuite(fileName: string, yaml: string): string {
    const filePath = join(suiteTmpDir, fileName);
    writeFileSync(filePath, yaml);
    const result = transpileYamlContent(yaml, filePath, { version: '0.0.1-test' });
    assert.equal(result.valid, true, `transpile failed: ${result.errors.join(', ')}`);
    return readFileSync(result.specFile!, 'utf-8');
  }

  it('emits baseURL for a top-level base_url on a suite file', () => {
    const content = transpileSuite('top-level.test.yaml', `
name: Repro
base_url: https://example.com
${suiteBody}`);

    assert.match(content, /test\.use\(/);
    assert.match(content, /"baseURL": "https:\/\/example\.com"/);
  });

  it('still honors the nested suite.base_url written by suiteToYaml', () => {
    const content = transpileSuite('nested.test.yaml', `
name: Repro
suite:
  base_url: https://nested.example.com
  tests:
    - name: anything
      statements:
        - VERIFY: ok
          js: "await expect(page).toHaveURL(/example/)"
`);

    assert.match(content, /"baseURL": "https:\/\/nested\.example\.com"/);
  });

  it('merges base_url alongside other use: keys instead of replacing them', () => {
    const content = transpileSuite('with-use.test.yaml', `
name: Repro
base_url: https://example.com
use:
  extensionDir: ./dist
${suiteBody}`);

    assert.match(content, /"baseURL": "https:\/\/example\.com"/);
    assert.match(content, /"extensionDir": "\.\/dist"/);
  });

  it('lets base_url take precedence over use.baseURL, matching single-test files', () => {
    const content = transpileSuite('precedence.test.yaml', `
name: Repro
base_url: https://wins.example.com
use:
  baseURL: https://loses.example.com
${suiteBody}`);

    assert.match(content, /"baseURL": "https:\/\/wins\.example\.com"/);
    assert.doesNotMatch(content, /loses\.example\.com/);
  });

  it('emits no test.use block when a suite sets neither base_url nor use', () => {
    const content = transpileSuite('bare.test.yaml', `
name: Repro
${suiteBody}`);

    assert.doesNotMatch(content, /test\.use\(/);
  });
});

/**
 * Regression tests for the follow-up to issue #2209 — file-level
 * `test.use({ baseURL })` does NOT reach worker-scoped beforeAll/afterAll hooks.
 *
 * Those hooks build their own page from `workerInfo.project.use`, which
 * Playwright populates from playwright.config.ts only. A suite that sets
 * base_url and navigates relatively in beforeAll therefore kept failing with
 * `Invalid URL` even after base_url started reaching test.use().
 */
describe('suite base_url reaches worker-scoped hooks', () => {
  const hookTmpDir = join(tmpdir(), 'suite-hook-baseurl-' + Date.now());
  mkdirSync(hookTmpDir, { recursive: true });

  after(() => {
    rmSync(hookTmpDir, { recursive: true, force: true });
  });

  function transpileSuite(fileName: string, yaml: string): string {
    const filePath = join(hookTmpDir, fileName);
    writeFileSync(filePath, yaml);
    const result = transpileYamlContent(yaml, filePath, { version: '0.0.1-test' });
    assert.equal(result.valid, true, `transpile failed: ${result.errors.join(', ')}`);
    return readFileSync(result.specFile!, 'utf-8');
  }

  it('uses the file-level base_url for the beforeAll page, not just the project config', () => {
    const content = transpileSuite('hook-baseurl.test.yaml', `
name: Repro
base_url: https://example.com
suite:
  beforeAll:
    - URL: /login
  tests:
    - name: anything
      statements:
        - VERIFY: ok
          js: "await expect(page).toHaveURL(/example/)"
`);

    const hookLine = content.split('\n').find(l => l.includes('browser.newPage('))!;
    assert.ok(hookLine, 'beforeAll must create a page');
    assert.match(hookLine, /https:\/\/example\.com/, 'hook page must carry the file-level baseURL');
  });

  it('does the same for afterAll', () => {
    const content = transpileSuite('hook-baseurl-after.test.yaml', `
name: Repro
base_url: https://example.com
suite:
  afterAll:
    - URL: /logout
  tests:
    - name: anything
      statements:
        - VERIFY: ok
          js: "await expect(page).toHaveURL(/example/)"
`);

    const hookLine = content.split('\n').find(l => l.includes('browser.newPage('))!;
    assert.match(hookLine, /https:\/\/example\.com/);
  });

  it('falls back to the project config baseURL when the suite sets no base_url', () => {
    const content = transpileSuite('hook-no-baseurl.test.yaml', `
name: Repro
suite:
  beforeAll:
    - URL: https://example.com/login
  tests:
    - name: anything
      statements:
        - VERIFY: ok
          js: "await expect(page).toHaveURL(/example/)"
`);

    const hookLine = content.split('\n').find(l => l.includes('browser.newPage('))!;
    assert.match(hookLine, /workerInfo\.project\.use\.baseURL/);
  });

  it('honors a use.baseURL set without base_url', () => {
    const content = transpileSuite('hook-use-baseurl.test.yaml', `
name: Repro
use:
  baseURL: https://from-use.example.com
suite:
  beforeAll:
    - URL: /login
  tests:
    - name: anything
      statements:
        - VERIFY: ok
          js: "await expect(page).toHaveURL(/example/)"
`);

    const hookLine = content.split('\n').find(l => l.includes('browser.newPage('))!;
    assert.match(hookLine, /https:\/\/from-use\.example\.com/);
  });
});
