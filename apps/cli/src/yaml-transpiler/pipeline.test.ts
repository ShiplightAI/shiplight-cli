    const yaml = `
goal: Login test
statements:
  - action: go_to_url
    intent: Navigate to login page
    url: https://example.com/login
    locator: "page"
    xpath: html/body
  - action: click
    intent: Click login button
    locator: "getByRole('button', { name: 'Login' })"
    xpath: html/body/div/button
`;
    const filePath = join(tmpDir, 'simple.test.yaml');
    writeFileSync(filePath, yaml);

    const result = transpileYamlContent(yaml, filePath, { version: '0.0.1-test' });

    assert.equal(result.valid, true);
    assert.deepEqual(result.errors, []);
    assert.ok(result.specFile);

    const content = readFileSync(result.specFile!, 'utf-8');
    assert.ok(content.includes('shiplightai/fixture'));
    assert.ok(content.includes('Login test'));
    assert.ok(content.includes('@generated by shiplightai v0.0.1-test'));
