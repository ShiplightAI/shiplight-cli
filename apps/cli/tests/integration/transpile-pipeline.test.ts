  test('transpiles suite tags from YAML text, at both file and per-test level', async () => {
    // The per-test `tags:` read at yamlParser.ts was dead code until the
    // transpiler started emitting it, and every other suite-tag test builds a
    // ParsedSuite by hand. This exercises the real YAML text -> spec file path,
    // so a parser change that stops reading `tags` fails here.
    await withTempDir((dir) => {
      writeFileSync(join(dir, 'suite.test.yaml'), `
name: Inventory Suite
tags:
  - smoke
base_url: https://example.com
suite:
  tests:
    - name: Sort products
      tags:
        - auth
        - "@slow path"
        - 2026
      statements:
        - intent: Sort by price
    - name: Scalar tag test
      tags: solo
      statements:
        - intent: Do something else
    - name: Untagged test
      statements:
        - intent: Do something
`);

      transpileAllYamlTests({ cwd: dir });

      const code = readFileSync(join(dir, 'suite.yaml.spec.ts'), 'utf-8');

      expect(code).toContain("test.describe.serial('Inventory Suite', { tag: ['@smoke'] }, () => {");
      // Per-test tags emitted; the already-quoted "@slow path" is not doubled,
      // and the unquoted `2026` arrives from the YAML parser as a number — this
      // is the real-text version of the coercion the unit test casts by hand.
      expect(code).toContain("test('Sort products', { tag: ['@auth', '@slow path', '@2026'] }, async (");
      // A bare scalar `tags: solo` behaves like a one-element list, as it does
      // at file level — the two spellings must not diverge.
      expect(code).toContain("test('Scalar tag test', { tag: ['@solo'] }, async (");
      expect(code).toContain("test('Untagged test', async (");
      expect(code).not.toContain('@@');
      expect(code).not.toContain("test('@auth");
    });
  });

