  test.describe('caching', () => {
    test('skips transpilation when output is up-to-date', async () => {
      await withTempDir((dir) => {
        writeFileSync(join(dir, 'cached.test.yaml'), `
goal: Cache test
base_url: https://example.com
statements:
  - intent: Step one
`);

        // First run: generates the file
        transpileAllYamlTests({ cwd: dir });
        const outPath = join(dir, 'cached.yaml.spec.ts');
        expect(existsSync(outPath)).toBe(true);

        const firstContent = readFileSync(outPath, 'utf-8');
        const firstMtime = statSync(outPath).mtimeMs;

        // Small delay to ensure mtime would differ if rewritten
        const past = new Date(Date.now() - 2000);
        utimesSync(join(dir, 'cached.test.yaml'), past, past);

        // Second run: should skip (YAML is older than output)
        transpileAllYamlTests({ cwd: dir });
        const secondMtime = statSync(outPath).mtimeMs;
        const secondContent = readFileSync(outPath, 'utf-8');

        expect(secondMtime).toBe(firstMtime);
        expect(secondContent).toBe(firstContent);
      });
    });

    test('re-transpiles a spec generated under an older output-format revision', async () => {
        // The whole point of OUTPUT_FORMAT_REVISION: when the emitted code
        // changes shape but the package version has not moved (it is always
        // `dev` from source), only the header can invalidate the cached spec.
        // Without this, a spec still carrying the old `test('@smoke X', ...)`
        // form is kept forever and CI runs code the YAML no longer describes.
        await withTempDir((dir) => {
          writeFileSync(join(dir, 'fmt.test.yaml'), `
goal: Format revision test
base_url: https://example.com
statements:
  - intent: Step one
`);

          transpileAllYamlTests({ cwd: dir });
          const outPath = join(dir, 'fmt.yaml.spec.ts');
          const current = readFileSync(outPath, 'utf-8');

          // Same package version, older format revision. The spec's mtime stays
          // newer than the YAML, so mtime alone would keep it.
          writeFileSync(
            outPath,
            current.replace(/^\/\/ @generated by shiplightai v.*$/m, '// @generated by shiplightai vdev+fmt1'),
          );
          const past = new Date(Date.now() - 5000);
          utimesSync(join(dir, 'fmt.test.yaml'), past, past);

          transpileAllYamlTests({ cwd: dir });

          expect(readFileSync(outPath, 'utf-8')).toBe(current);
      });
    });

    test('re-transpiles when YAML source changes', async () => {
      await withTempDir((dir) => {
        writeFileSync(join(dir, 'changing.test.yaml'), `
goal: Original
base_url: https://example.com
statements:
  - intent: Original step
`);

        transpileAllYamlTests({ cwd: dir });
        const outPath = join(dir, 'changing.yaml.spec.ts');
        const firstContent = readFileSync(outPath, 'utf-8');
        expect(firstContent).toContain('Original');

        // Set the output file's mtime to the past so the source is newer
        const past = new Date(Date.now() - 5000);
        utimesSync(outPath, past, past);

        // Modify the YAML source (touch it to update mtime)
        writeFileSync(join(dir, 'changing.test.yaml'), `
goal: Updated
base_url: https://example.com
statements:
  - intent: Updated step
`);

        transpileAllYamlTests({ cwd: dir });
        const secondContent = readFileSync(outPath, 'utf-8');
        expect(secondContent).toContain('Updated');
        expect(secondContent).not.toContain("test('Original'");
      });
    });

    test('re-transpiles when referenced template changes', async () => {
      await withTempDir((dir) => {
        const templatePath = join(dir, 'shared.yaml');
        writeFileSync(templatePath, `
statements:
  - intent: Original template step
`);

        writeFileSync(join(dir, 'uses-template.test.yaml'), `
goal: Template cache test
base_url: https://example.com
statements:
  - template: ./shared.yaml
`);

        transpileAllYamlTests({ cwd: dir });
        const outPath = join(dir, 'uses-template.yaml.spec.ts');
        const firstContent = readFileSync(outPath, 'utf-8');
        expect(firstContent).toContain('Original template step');

        // Set output mtime to past
        const past = new Date(Date.now() - 5000);
        utimesSync(outPath, past, past);

        // Update the template (newer mtime than output)
        writeFileSync(templatePath, `
statements:
  - intent: Updated template step
`);

        transpileAllYamlTests({ cwd: dir });
        const secondContent = readFileSync(outPath, 'utf-8');
        expect(secondContent).toContain('Updated template step');
      });
    });
  });

  test('handles invalid YAML gracefully — transpiles valid files and skips bad ones', async () => {
    await withTempDir((dir) => {
      // Valid file
      writeFileSync(join(dir, 'good.test.yaml'), `
goal: Good test
base_url: https://example.com
statements:
  - intent: Do something
`);

      // Invalid file (missing required fields)
      writeFileSync(join(dir, 'bad.test.yaml'), `
not_a_valid_field: true
`);

      // Global scan (no specific files requested) — warns and skips bad files.
      // When specific files are requested (e.g. CLI `--files bad.test.yaml`),
      // transpileAllYamlTests still throws for those. The skip-and-continue
      // behavior only applies to discovery scans so one bad file doesn't block
      // the entire project from transpiling.
      transpileAllYamlTests({ cwd: dir });

      // Good file should still be transpiled
      expect(existsSync(join(dir, 'good.yaml.spec.ts'))).toBe(true);

      // Bad file should not produce output
      expect(existsSync(join(dir, 'bad.yaml.spec.ts'))).toBe(false);
    });
  });

  test('generates syntactically valid TypeScript', async () => {
    await withTempDir((dir) => {
      // Complex YAML with multiple features
      writeFileSync(join(dir, 'complex.test.yaml'), `
name: Complex E2E Test
tags:
  - regression
use:
  locale: fr-FR
goal: Full feature test
base_url: https://example.com
statements:
  - STEP: Setup
    statements:
      - intent: Navigate to the app
      - VERIFY: App is loaded

  - intent: Click Submit
    action: click
    locator: "getByRole('button', { name: 'Submit' })"

  - IF: "js: page.url().includes('/success')"
    THEN:
      - VERIFY: Success page is shown
    ELSE:
      - intent: Retry the submission

teardown:
  - intent: Clean up test data
`);

      transpileAllYamlTests({ cwd: dir });

      const code = readFileSync(join(dir, 'complex.yaml.spec.ts'), 'utf-8');

      // Check structural validity: balanced braces
      const opens = (code.match(/\{/g) || []).length;
      const closes = (code.match(/\}/g) || []).length;
      expect(opens).toBe(closes);

      // Check structural validity: balanced parens
      const openParens = (code.match(/\(/g) || []).length;
      const closeParens = (code.match(/\)/g) || []).length;
      expect(openParens).toBe(closeParens);

      // Ends properly
      expect(code.trimEnd()).toMatch(/\}\);$/);
    });
  });
